/**
 * Generates src/lib/poker/integrity-data.ts: the integrity lab's baseline and players, simulated and
 * analysed by src/lib/poker/integrity.ts. Takes about 15 seconds, which is too slow for page load.
 * tests/integrity.test.ts recomputes part of it and fails if the checked-in data is out of date.
 *
 * Run from the repository root:
 *   npx rolldown scripts/integrity-lab.ts --platform node --file /tmp/integrity-lab.mjs
 *   node /tmp/integrity-lab.mjs
 */
import { writeFileSync } from "node:fs";
import { labSteps } from "../src/lib/poker/integrity";

const steps = labSteps();
let next = steps.next();
while (!next.done) {
  process.stdout.write(`\r${next.value.done}/${next.value.total} players`);
  next = steps.next();
}
process.stdout.write("\n");
writeFileSync(
  "src/lib/poker/integrity-data.ts",
  `// Generated by scripts/integrity-lab.ts. Do not edit by hand.\nimport type { LabResult } from "./integrity";\n\nexport const LAB_DATA: LabResult = ${JSON.stringify(next.value)};\n`,
);
